import assert from 'node:assert/strict'
import { runAiProviderLayoutChecks } from '../../options/options-ai-provider-layout-scenarios.mjs'

export async function runActionFeedbackChecks(page, origin, directory, startAt = 'controls') {
  const report = { checks: [], screenshots: [] }
  const surfaces = ['controls', 'options', 'popup', 'sidepanel', 'newtab']
  assert.ok(surfaces.includes(startAt))
  const shouldRun = surface => surfaces.indexOf(surface) >= surfaces.indexOf(startAt)
  const copy = 'button[aria-label^="复制书签链接"]'
  const pass = name => { report.checks.push(name); console.log(`PASS ${name}`) }
  const navigate = async surface => {
    await page.goto(`${origin}/?surface=${surface}`)
    await page.waitForFunction(() => Boolean(window.__actionFixture))
    await page.waitForSelector(surface === 'newtab' ? '.bookmark-edit-menu' : '#root button')
    console.log(await page.snapshot())
  }
  const viewport = (width, height = 960) => page.cdp('Emulation.setDeviceMetricsOverride', {
    width, height, deviceScaleFactor: 1, mobile: false
  })
  const phase = (selector, state) => page.waitForFunction(({ selector, state }) => {
    return document.querySelector(selector)?.getAttribute('data-feedback-state') === state
  }, { selector, state }, { timeout: 5000 })
  const holdPhase = state => page.waitForFunction(state =>
    document.querySelector('#hold-button')?.getAttribute('data-hold-phase') === state, state, { timeout: 4000 })
  const count = () => page.evaluate(() => window.__actionFixture.confirmed)
  const complete = success => page.evaluate(success => window.__actionFixture.complete(success), success)
  const activate = async selector => {
    await page.focus(selector)
    await page.press(selector, 'Enter')
  }
  const width = selector => page.evaluate(selector => document.querySelector(selector).offsetWidth, selector)
  const assertNoErrors = async () => assert.deepEqual(await page.evaluate(() => window.__actionFixture.errors), [])
  const resetHold = async () => {
    await page.evaluate(() => window.__actionFixture.resetHold())
    await holdPhase('idle')
  }
  const pointerDown = async (selector = '#hold-button') => {
    await page.hover(selector)
    const rect = await page.evaluate(selector => {
      const rect = document.querySelector(selector).getBoundingClientRect()
      return { x: rect.x + rect.width / 2, y: rect.y + rect.height / 2, right: rect.right }
    }, selector)
    await page.mouse.move(rect.x, rect.y)
    await page.mouse.down()
    return rect
  }
  const shot = async name => {
    await page.waitForFunction(() => document.getAnimations().every(animation =>
      animation.effect?.getTiming().iterations === Infinity || animation.playState !== 'running'
    ), undefined, { timeout: 4000 })
    const filename = `${directory}/${name}.png`
    await page.screenshot({ path: filename })
    report.screenshots.push(filename)
  }
  if (shouldRun('controls')) {
  await viewport(1280)
  await page.cdp('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'no-preference' }] })
  await navigate('controls')
  const initialWidth = await width('#status-button')
  await page.click('#status-button')
  await phase('#status-button', 'pending')
  assert.equal(await page.evaluate(() => document.activeElement.id), 'status-button', 'loading retains focus')
  await page.keyboard.press('Enter')
  assert.equal(await page.evaluate(() => window.__actionFixture.calls), 1, 'busy controls ignore repeated activation')
  assert.equal(await width('#status-button'), initialWidth)
  await complete(false)
  await phase('#status-button', 'error')
  assert.equal(await width('#status-button'), initialWidth)
  await page.click('#status-button')
  await phase('#status-button', 'pending')
  await complete(true)
  await phase('#status-button', 'success')
  assert.equal(await width('#status-button'), initialWidth)
  await shot('controls-success')
  await phase('#status-button', 'idle')
  pass('status buttons: real pending/error/success, retry, bounded reset, fixed width and retained focus')

  await page.fill('#fixture-key', 'sk-editable-fixture')
  await page.click('#fixture-key-reveal')
  assert.equal(await page.evaluate(() => document.querySelector('#fixture-key').type), 'text')
  assert.equal(await page.evaluate(() => document.querySelector('#fixture-key').value), 'sk-editable-fixture')
  await page.keyboard.press('Escape')
  assert.equal(await page.evaluate(() => document.querySelector('#fixture-key').type), 'password')
  await page.click('#fixture-key-reveal')
  await page.click('#outside-button')
  assert.equal(await page.evaluate(() => document.querySelector('#fixture-key').type), 'password')
  await page.click('#fixture-key-reveal')
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  assert.equal(await page.evaluate(() => document.querySelector('#fixture-key').type), 'password')
  pass('editable key: reveal toggle, Escape, focus leaving and window blur hide the value')

  await page.focus('#hold-button')
  await page.keyboard.press('Enter')
  await holdPhase('idle')
  assert.equal(await count(), 0, 'short Enter does not act like an assistive click')
  await page.keyboard.press('Space')
  await holdPhase('idle')
  assert.equal(await count(), 0)
  await pointerDown()
  await holdPhase('holding')
  await page.mouse.up()
  await holdPhase('idle')
  assert.equal(await count(), 0)
  let rect = await pointerDown()
  await page.mouse.move(rect.right + 80, rect.y)
  await page.mouse.up()
  await holdPhase('idle')
  assert.equal(await count(), 0)
  rect = await pointerDown()
  await holdPhase('ready')
  assert.equal(await count(), 0, 'the threshold only arms; release is required')
  await page.mouse.move(rect.right + 80, rect.y)
  await page.mouse.up()
  await holdPhase('idle')
  assert.equal(await count(), 0)
  pass('hold cancellation: short pointer/key press and moving outside even after the threshold')

  await page.focus('#hold-button')
  await page.keyboard.down('Space')
  await page.focus('#outside-button')
  await page.keyboard.up('Space')
  await holdPhase('idle')
  await pointerDown()
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  await page.mouse.up()
  await holdPhase('idle')
  await pointerDown()
  await page.evaluate(() => window.__actionFixture.disableHold(true))
  await page.mouse.up()
  await holdPhase('idle')
  assert.equal(await count(), 0)
  await resetHold()
  await pointerDown()
  await page.evaluate(() => window.__actionFixture.unmountHold())
  await page.mouse.up()
  await resetHold()
  await page.focus('#hold-button')
  await page.keyboard.down('Enter')
  await page.keyboard.down('Enter')
  await holdPhase('ready')
  assert.equal(await count(), 0)
  await page.keyboard.up('Enter')
  assert.equal(await count(), 1)
  await page.keyboard.press('Enter')
  assert.equal(await count(), 1)
  pass('hold lifecycle: blur, window exit, disabled and unmount cancel; held Enter fires once on release')

  await resetHold()
  await pointerDown()
  await holdPhase('ready')
  await shot('controls-hold-ready')
  await page.mouse.up()
  assert.equal(await count(), 2)
  await resetHold()
  await page.evaluate(() => document.querySelector('#hold-button').click())
  await holdPhase('ready')
  assert.equal(await count(), 2)
  await page.evaluate(() => document.querySelector('#hold-button').click())
  assert.equal(await count(), 3)
  pass('hold completion: pointer release and untimed two-activation assistive fallback')

  await page.cdp('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
  await page.click('#status-button')
  await phase('#status-button', 'pending')
  assert.equal(await page.evaluate(() => getComputedStyle(document.querySelector('.curator-action-spinner')).animationName), 'none')
  await complete(true)
  await phase('#status-button', 'success')
  assert.equal(await page.evaluate(() => getComputedStyle(document.querySelector('.curator-action-icon > .t-icon')).transitionDuration), '0s')
  await resetHold()
  await pointerDown()
  await holdPhase('holding')
  assert.equal(await page.evaluate(() => getComputedStyle(document.querySelector('.curator-hold-fill')).animationName), 'none')
  await holdPhase('ready')
  await page.mouse.up()
  assert.equal(await count(), 4, 'reduced motion does not shorten the confirmation threshold')
  await assertNoErrors()
  pass('reduced motion: no spin, icon transition or filling animation; confirmation semantics unchanged')
  }

  if (shouldRun('options')) {
  const layoutReport = await runAiProviderLayoutChecks(page, origin, directory)
  report.checks.push(...layoutReport.checks)
  report.screenshots.push(...layoutReport.screenshots)
  await page.cdp('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'no-preference' }] })
  await viewport(1440, 1100)
  await navigate('options')
  await page.fill('#ai-api-key', 'sk-options-fixture')
  await page.click('#ai-api-key-reveal')
  assert.equal(await page.evaluate(() => document.querySelector('#ai-api-key').type), 'text')
  const test = 'button[aria-label^="测试自定义 AI 渠道连接"]'
  const fetch = 'button[aria-label^="从自定义 AI 渠道获取模型列表"]'
  const testWidth = await width(test)
  await page.click(test)
  await phase(test, 'pending')
  assert.equal(await page.evaluate(() => document.querySelector('#ai-api-key').type), 'password')
  assert.equal(await page.evaluate(() => document.querySelectorAll('.curator-action-spinner').length), 1, 'busy feedback is not duplicated in status copy')
  await complete(false)
  await phase(test, 'error')
  assert.equal(await width(test), testWidth)
  assert.ok(await page.evaluate(() => document.body.textContent.includes('测试服务暂时不可用。')))
  await activate(fetch)
  await phase(fetch, 'pending')
  await complete(true)
  await phase(fetch, 'success')
  for (const [label, success] of [
    ['导出书签标签数据', true], ['导出完整书签备份', true], ['导出通用 HTML 书签文件', false]
  ]) {
    const button = `button[aria-label^="${label}"]`
    const originalWidth = await width(button)
    await activate(button)
    await phase(button, 'pending')
    assert.equal(await page.evaluate(() => document.querySelectorAll('.curator-action-spinner').length), 1)
    await complete(success)
    await phase(button, success ? 'success' : 'error')
    assert.equal(await width(button), originalWidth)
  }
  await page.keyboard.press('Control+Home')
  await shot('options-desktop')
  pass('production settings: connection, model fetch and all three exports render their own results')

  await activate('button[aria-label="清空全部书签标签数据"]')
  await page.waitForSelector('[role="dialog"] #confirm-modal-title')
  assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), '取消当前确认操作')
  assert.ok(await page.evaluate(() => document.querySelector('#confirm-modal-title').textContent.includes('3')))
  await page.click('.curator-hold-button')
  assert.equal(await count(), 0)
  await page.keyboard.press('Escape')
  await page.waitForFunction(() => !document.querySelector('.curator-hold-button'))
  await activate('button[aria-label="清空全部书签标签数据"]')
  await pointerDown('.curator-hold-button')
  await page.waitForFunction(() => document.querySelector('.curator-hold-button')?.dataset.holdPhase === 'ready')
  await shot('options-hold-dialog')
  await page.mouse.up()
  await page.waitForFunction(() => window.__actionFixture.confirmed === 1)
  pass('production clear dialog: count and consequence retained, Cancel focused first, only a full hold confirms')

  await viewport(390, 1000)
  await page.keyboard.press('Control+Home')
  await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth)
  await shot('options-narrow')
  await assertNoErrors()
  pass('settings fit a 390px viewport without horizontal overflow')
  }

  if (shouldRun('popup')) {
  await viewport(720, 520)
  await navigate('popup')
  await page.click(copy)
  await phase(copy, 'pending')
  const focusedCopy = await page.evaluate(() => document.activeElement.getAttribute('aria-label'))
  assert.ok(focusedCopy.startsWith('复制书签链接'))
  await complete(true)
  await phase(copy, 'success')
  assert.equal(await page.evaluate(selector => document.querySelector(selector).title, copy), '已复制')
  assert.ok(await page.evaluate(() => document.activeElement.getAttribute('aria-label').startsWith('复制书签链接')))
  await shot('popup-copy')
  await phase(copy, 'idle')
  await page.click(copy)
  await complete(false)
  await phase(copy, 'error')
  await assertNoErrors()
  pass('production Popup action rail: copy result survives memoization, retains focus and resets')
  }

  if (shouldRun('sidepanel')) {
  await viewport(720, 520)
  await navigate('sidepanel')
  await page.click('button[aria-label="打开书签操作"]')
  await page.click(copy)
  await phase(copy, 'pending')
  await complete(true)
  await phase(copy, 'success')
  assert.ok(await page.evaluate(() => Boolean(document.querySelector('[data-popup-row-menu]'))))
  await shot('sidepanel-copy')
  await assertNoErrors()
  pass('sidepanel copy stays open to show its result')
  }

  await viewport(1000, 800)
  await navigate('newtab')
  const menuWidth = await width('.bookmark-edit-menu')
  await page.focus(copy)
  await page.keyboard.press('Enter')
  await page.waitForSelector('.curator-action-icon[data-feedback-state="pending"]')
  assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), '复制书签链接：设计参考')
  await complete(true)
  await page.waitForSelector('.curator-action-icon[data-feedback-state="success"]')
  assert.equal(await width('.bookmark-edit-menu'), menuWidth)
  assert.equal(await page.evaluate(() => document.querySelectorAll('.bookmark-menu-status').length), 0, 'no second success bubble')
  await shot('newtab-copy')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('ArrowRight')
  await page.waitForSelector('[role="menuitem"][aria-label="参考资料"]')
  await page.keyboard.press('ArrowLeft')
  await viewport(390, 800)
  await page.waitForFunction(() => {
    const rect = document.querySelector('.bookmark-edit-menu').getBoundingClientRect()
    return rect.left >= 0 && rect.right <= innerWidth
  })
  await shot('newtab-narrow')
  await assertNoErrors()
  pass('production New Tab: in-place result, keyboard focus, menu width and move submenu preserved')
  console.log(await page.snapshot())
  return report
}
